package urok3;

public class DataTypesPractice {
    public static void main(String[] args) {

        byte byteNumber = 23;
        System.out.println("byte: " + byteNumber);
        short shortNumber = 104;
        System.out.println("short: " + shortNumber);
        int intNumber = 678800;
        System.out.println("int: " + intNumber);
        long longNumber = 10939884733473800L;
        System.out.println("long: " + longNumber);
        float floatNumber = 7.3f;
        System.out.println("float: " + floatNumber);
        double doubleNumber = 90.15;
        System.out.println("double: " + doubleNumber);
        char grade = 'B';
        System.out.println("char: " + grade);
        boolean likesJava = true;
        System.out.println("boolean: " + likesJava);
        String text = "Java";
        System.out.println("String: " + text);
    }
}

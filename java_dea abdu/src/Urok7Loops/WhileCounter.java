package Urok7Loops;

public class WhileCounter {
    public static void main(String[] args) {
        int number = 1;
        while (number < 10) {
            System.out.println(number);
            number++;
        }
        number=10;
        while (number>=1) {
            System.out.println(number);
            number--;
        }
        System.out.println("Start");
    }

}